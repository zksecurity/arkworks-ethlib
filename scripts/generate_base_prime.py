#!/usr/bin/env python3
"""Render a Lucas certificate as ordinary Lean proofs; no external solver is trusted."""
import argparse
import json
from math import prod
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / 'provenance/bls12-381-base-prime.json'
OUTPUT = ROOT / 'curve/BasePrimeProof.lean'

HEADER = '''import Mathlib.NumberTheory.LucasPrimality
import Mathlib.Data.List.Prime
import Mathlib.Tactic.ReduceModChar
import Mathlib.Tactic.NormNum.Prime
import EthLib.Cryptography.Bls.Fp

/-! Generated by scripts/generate_base_prime.py from explicit Lucas certificate data.
Every factor, modular-power equation and non-equation is checked by Lean's kernel.
The discovery software is outside the proof; rebuilding requires only Lean/Mathlib. -/

namespace BasePrime

private theorem from_lucas (n : Nat) (a : ZMod n) (factors : List Nat)
    (hproduct : factors.prod = n-1)
    (hprimes : ∀ q ∈ factors, Nat.Prime q)
    (hpower : a^(n-1) = 1)
    (horders : ∀ q ∈ factors, a^((n-1)/q) ≠ 1) : Nat.Prime n := by
  apply lucas_primality n a hpower
  intro q hq hdvd
  apply horders q
  apply mem_list_primes_of_dvd_prod hq.prime (fun r hr => (hprimes r hr).prime)
  rwa [hproduct]

'''


def render(data_path=DATA, scalar=False):
    data = json.loads(data_path.read_text())
    nodes = sorted(data['nodes'], key=lambda node: int(node['n']))
    indices = {int(node['n']): i for i, node in enumerate(nodes)}
    if len(indices) != len(nodes):
        raise ValueError('Duplicate certificate node')
    pieces = [HEADER]
    for i, node in enumerate(nodes):
        n, g = int(node['n']), int(node['witness'])
        pairs = [(int(f['prime']), int(f['exponent'])) for f in node['factors']]
        if not (n > 2 and 1 < g < n and all(2 <= q < n and e > 0 for q, e in pairs)):
            raise ValueError(f'Invalid certificate node {n}')
        if len({q for q, _ in pairs}) != len(pairs):
            raise ValueError(f'Duplicate factor in node {n}')
        if prod(q**e for q, e in pairs) != n-1:
            raise ValueError(f'Factorization mismatch at node {n}')
        if pow(g, n-1, n) != 1 or any(pow(g, (n-1)//q, n) == 1 for q, _ in pairs):
            raise ValueError(f'Invalid Lucas witness at node {n}')
        for q, _ in pairs:
            if q >= 1000 and (q not in indices or indices[q] >= i):
                raise ValueError(f'Missing earlier factor certificate for {q}')
        factors = [q for q, e in pairs for _ in range(e)]
        orders = {q: f'order_{i}_{j}' for j, (q, _) in enumerate(pairs)}
        pieces.append(f'-- Certificate node {i}: {n}.\n')
        pieces.append(f'private theorem power_{i} : ({g} : ZMod {n})^{n-1} = 1 := by\n  reduce_mod_char\n\n')
        for q, _ in pairs:
            pieces.append(f'private theorem {orders[q]} : ({g} : ZMod {n})^{(n-1)//q} ≠ 1 := by\n  reduce_mod_char\n  decide +kernel\n\n')
        pieces.append(f'private theorem prime_{i} : Nat.Prime {n} := by\n')
        pieces.append(f'  apply from_lucas {n} ({g} : ZMod {n}) [{", ".join(map(str, factors))}]\n')
        pieces.append('  · decide +kernel\n  · intro q hq\n    simp only [List.mem_cons, List.not_mem_nil, or_false] at hq\n')
        cases = ' | '.join('rfl' for _ in factors)
        pieces.append(f'    rcases hq with {cases}\n')
        for q in factors:
            proof = 'norm_num' if q < 1000 else f'exact prime_{indices[q]}'
            pieces.append(f'    · {proof}\n')
        pieces.append(f'  · exact power_{i}\n  · intro q hq\n    simp only [List.mem_cons, List.not_mem_nil, or_false] at hq\n')
        pieces.append(f'    rcases hq with {cases}\n')
        pieces.extend(f'    · exact {orders[q]}\n' for q in factors)
        pieces.append('\n')
    modulus = int(data['modulus'])
    if modulus not in indices:
        raise ValueError('Missing base modulus certificate')
    pieces.append('/-- The BLS12-381 base-field modulus used by unchanged EthLib is prime. -/\n')
    pieces.append('theorem modulus_prime : Nat.Prime EthLib.Cryptography.Bls.Fp.modulus :=\n')
    pieces.append(f'  prime_{indices[modulus]}\n\n#print axioms modulus_prime\nend BasePrime\n')
    rendered = ''.join(pieces)
    if scalar:
        rendered = rendered.replace("BasePrime", "ScalarPrime").replace("Bls.Fp", "Bls.Fr")
        rendered = rendered.replace("base-field modulus", "scalar-field modulus")
    return rendered


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Check the committed rendering')
    parser.add_argument('--scalar', action='store_true', help='Render the scalar-field certificate')
    args = parser.parse_args()
    output = ROOT / 'curve/ScalarPrimeProof.lean' if args.scalar else OUTPUT
    data = ROOT / 'provenance/bls12-381-scalar-prime.json' if args.scalar else DATA
    rendered = render(data, scalar=args.scalar)
    if args.check:
        if output.read_text() != rendered:
            raise SystemExit('Primality proof is out of date; regenerate it')
        print(f'PASS: {output.name} matches the explicit certificate data.')
    else:
        output.write_text(rendered)
        print(f'Wrote {output.relative_to(ROOT)} ({len(rendered.splitlines())} lines).')


if __name__ == '__main__':
    main()
